#!/usr/bin/env node
// Regenerate lib/zoning/councils.ts. Run: npm run build:zoning
//
// New Zealand has no national district-plan service — zoning is published by
// each of the 67 territorial authorities separately, mostly as ArcGIS REST.
// district-plans.nz catalogues all of them, so the registry is generated from
// that rather than hand-maintained: 67 councils change their endpoints often
// enough that a hand-written list would rot, and silently.
//
// Checked in rather than fetched at runtime, deliberately. A report must not
// depend on a third-party catalogue being up, and the endpoints change on the
// order of months, not minutes.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const CATALOGUE = "https://district-plans.nz/data/nz_district_plans.csv";
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const OUT = path.join(root, "lib/zoning/councils.ts");

/** Minimal CSV reader — the catalogue quotes fields containing commas. */
function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false;
      } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
    else if (c !== "\r") field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const header = rows.shift();
  return rows
    .filter((r) => r.length === header.length)
    .map((r) => Object.fromEntries(header.map((h, i) => [h, r[i]])));
}

/**
 * Pick the layer that carries the zones.
 *
 * `layer_names` reads like "Zones (14); Residential Zones (65); Rural Zones (66)".
 * The general layer is the one we want — the themed ones only hold their own
 * slice, so a rural property would miss entirely against "Residential Zones".
 * Preference therefore goes to the plainest name, then to the first listed.
 */
function pickLayer(layerNames) {
  const entries = (layerNames || "")
    .split(";")
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => {
      const m = s.match(/^(.*?)\s*\((\d+)\)\s*$/);
      return m ? { name: m[1].trim(), index: Number(m[2]) } : { name: s, index: null };
    });
  if (entries.length === 0) return null;
  const generic = entries.find((e) => /^(district plan )?zon(e|es|ing)$/i.test(e.name));
  return generic ?? entries[0];
}

const res = await fetch(CATALOGUE);
if (!res.ok) {
  console.error(`Catalogue fetch failed: HTTP ${res.status}`);
  process.exit(1);
}
const rows = parseCsv(await res.text());

const councils = [];
let skipped = 0;
for (const r of rows) {
  const arcgis = /arcgis rest/i.test(r.layer_access || "");
  const layer = pickLayer(r.layer_names);
  if (!arcgis || !r.zone_layer_url || !layer) {
    skipped++;
    continue;
  }
  councils.push({
    territory: r.territory,
    service: r.zone_layer_url.replace(/\/+$/, ""),
    layer: layer.index,
    layerName: layer.name,
    rulesUrl: r.zone_rules_url || null,
  });
}
councils.sort((a, b) => a.territory.localeCompare(b.territory));

const body = `// GENERATED by scripts/build-zoning-registry.mjs — do not edit by hand.
// Source: ${CATALOGUE} (district-plans.nz), retrieved ${new Date().toISOString().slice(0, 10)}.
//
// Data ownership, licensing and currency remain with each council. ${councils.length} of
// ${rows.length} territorial authorities publish their zones as a queryable ArcGIS REST
// service; the remaining ${rows.length - councils.length} offer only static maps, viewers or bulk
// downloads, and for those the report has to say plainly that it could not
// retrieve the zone rather than invent one or send the reader off to look.

export interface ZoningCouncil {
  /** Matches LINZ's \`territorial_authority\` on the address layer. */
  territory: string;
  service: string;
  /** Layer index within the service; null when the catalogue didn't name one. */
  layer: number | null;
  layerName: string;
  /** The council's own plan page, for a citation the reader can follow. */
  rulesUrl: string | null;
}

export const ZONING_COUNCILS: ZoningCouncil[] = ${JSON.stringify(councils, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);
console.log(`Wrote ${councils.length} councils to lib/zoning/councils.ts (${skipped} without a queryable service).`);
