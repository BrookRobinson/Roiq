#!/usr/bin/env node
// Regenerate lib/linz/instrument-types.ts from LINZ. Run: npm run build:instruments
//
// LINZ's Transaction Type table turns the codes on a title into English — "EI"
// into "Easement Instrument", "LCOV" into "Land Transfer Plan Land Covenant".
// It is ~525 rows and changes about as often as the Land Transfer Act, so it is
// GENERATED AND CHECKED IN rather than fetched per report: two network calls per
// property is already two more than this feature had, and a report must not
// depend on a third-party catalogue answering before it can name what is
// registered against a title.
//
// Needs LINZ_API_KEY in .env.local.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));

function apiKey() {
  if (process.env.LINZ_API_KEY?.trim()) return process.env.LINZ_API_KEY.trim();
  const env = readFileSync(join(root, ".env.local"), "utf8");
  const m = /^LINZ_API_KEY=(.*)$/m.exec(env);
  if (!m) throw new Error("LINZ_API_KEY not found in .env.local");
  return m[1].trim().replace(/^["']|["']$/g, "");
}

const TRANSACTION_TYPE_TABLE = "table-52009";

const res = await fetch(
  `https://data.linz.govt.nz/services;key=${apiKey()}/wfs?service=WFS&version=2.0.0` +
    `&request=GetFeature&typeNames=${TRANSACTION_TYPE_TABLE}&outputFormat=json&count=2000`
);
if (!res.ok) throw new Error(`LINZ responded ${res.status}`);
const rows = (await res.json()).features.map((f) => f.properties);
console.log(`fetched ${rows.length} transaction types`);

const entries = rows
  .filter((r) => r.grp && r.type && r.description)
  .map((r) => [`${r.grp}/${r.type}`, r.description.trim()])
  .sort(([a], [b]) => a.localeCompare(b));

const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");

writeFileSync(
  join(root, "lib/linz/instrument-types.ts"),
  `// GENERATED by scripts/build-instrument-types.mjs — do not edit by hand.
// Source: Toitū Te Whenua LINZ, "Landonline: Transaction Type" (${TRANSACTION_TYPE_TABLE}),
// CC BY 4.0. Regenerate with: npm run build:instruments
//
// What every code registered against a title actually means, in English. Checked
// in rather than fetched: it changes about as often as the Land Transfer Act,
// and a report must not wait on a third-party catalogue to name what burdens a
// property.

/** "GRP/TYPE" → LINZ's own description of that instrument. */
export const INSTRUMENT_TYPES: Record<string, string> = {
${body}
};

/** How many descriptions the registry holds — used by the verifier. */
export const INSTRUMENT_TYPE_COUNT = ${entries.length};
`
);
console.log(`wrote lib/linz/instrument-types.ts (${entries.length} entries)`);
